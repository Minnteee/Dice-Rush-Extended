def main():
    for s in STEPS:
        run(s)
    env = dict(os.environ, PYTHONIOENCODING='utf-8')
    r = subprocess.run([PY, os.path.join(HERE, 'verify.py')], cwd=HERE, env=env, capture_output=True, text=True, encoding='utf-8')
    verify_out = r.stdout.strip()
    print(verify_out)
    rows = file_table()
    lines = [REPORT_HEAD, '\n## File list (%d files)\n' % len(rows), '| file | size |', '|---|---|']
    for rel, info in rows:
        lines.append('| `%s` | %s |' % (rel, info))
    lines.append('\n## verify.py\n```\n%s\n```\n' % verify_out)
    with open(os.path.join(ROOT, 'ART_REPORT.md'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print('report written,', len(rows), 'files')


if __name__ == '__main__':
    main()
