"""Re-generate every Dice Rush Extended art asset, verify it and write ART_REPORT.md.

Run:  tools/venv/Scripts/python.exe tools/art/build_all.py
Outputs go to build/generated/bdr/art/ (packed in game as res://bdr/art/...).
Review previews go to tools/art/_preview/.
"""
import glob
import json
import os
import subprocess
import sys
import time
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(REPO, "build", "generated", "bdr", "art")
PY = sys.executable
STEPS = ['gen_dice.py', 'gen_tarot.py', 'gen_cursors.py', 'gen_boards.py', 'gen_staff.py', 'gen_events_ui.py', 'preview_icons.py']


def run(script):
    t = time.time()
    env = dict(os.environ, PYTHONIOENCODING='utf-8')
    r = subprocess.run([PY, os.path.join(HERE, script)], cwd=HERE, env=env, capture_output=True, text=True, encoding='utf-8')
    print('%-18s %5.1fs  %s' % (script, time.time() - t, (r.stdout.strip().splitlines() or [''])[-1][:80]))
    if r.returncode != 0:
        print(r.stdout)
        print(r.stderr)
        raise SystemExit('step failed: ' + script)


def file_table():
    from PIL import Image
    rows = []
    for p in sorted(glob.glob(os.path.join(ROOT, '**', '*'), recursive=True)):
        if os.path.isdir(p) or p.endswith('.md'):
            continue
        rel = os.path.relpath(p, ROOT).replace('\\', '/')
        if p.endswith('.png'):
            with Image.open(p) as im:
                rows.append((rel, '%dx%d %s' % (im.size[0], im.size[1], im.mode)))
        else:
            rows.append((rel, '%d bytes' % os.path.getsize(p)))
    return rows


