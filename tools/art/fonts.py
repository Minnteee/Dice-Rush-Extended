# bold version of the small font: each 1px stroke doubled horizontally
def _parse(s):
    lines = [l for l in s.strip('\n').split('\n')]
    w = max(len(l) for l in lines)
    return np.array([[1 if (x < len(l) and l[x] == '#') else 0 for x in range(w)] for l in lines], np.uint8)


_cache = {}


def glyph_mask(font, ch):
    key = (id(font), ch)
    if key not in _cache:
        _cache[key] = _parse(font[ch])
    return _cache[key]


def text_mask(text, font, spacing=1, line_gap=2, bold=False):
    """Returns binary mask for (possibly multi-line, '/' separated) text."""
    lines = text.split('/')
    rendered = []
    for line in lines:
        ms = [glyph_mask(font, ch) for ch in line]
        if bold:
            ms2 = []
            for m in ms:
                m2 = np.zeros((m.shape[0], m.shape[1] + 1), np.uint8)
                m2[:, :-1] |= m
                m2[:, 1:] |= m
                ms2.append(m2)
            ms = ms2
        h = max(m.shape[0] for m in ms)
        w = sum(m.shape[1] for m in ms) + spacing * (len(ms) - 1)
        out = np.zeros((h, w), np.uint8)
        x = 0
        for m in ms:
            out[h - m.shape[0]:, x:x + m.shape[1]] = m
            x += m.shape[1] + spacing
        rendered.append(out)
    W = max(r.shape[1] for r in rendered)
    H = sum(r.shape[0] for r in rendered) + line_gap * (len(rendered) - 1)
    out = np.zeros((H, W), np.uint8)
    y = 0
    for r in rendered:
        x = (W - r.shape[1]) // 2
        out[y:y + r.shape[0], x:x + r.shape[1]] = r
        y += r.shape[0] + line_gap
    return out


def mask_to_rgba(mask, color):
    a = np.zeros(mask.shape + (4,), np.uint8)
    a[mask > 0] = hexc(color)
    return a


